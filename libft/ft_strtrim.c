#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*strt;
	size_t	start;
	size_t	end;

	if (!s1 || !set)
		return (NULL);
	start = 0;
	while (s1[start] && ft_strchr(set, s1[start]))
		start++;
	end = ft_strlen(s1) - 1;
	while (end > start && ft_strchr(set, s1[end]))
		end--;
	strt = (char *)malloc(end - start + 2);
	ft_memcpy(strt, s1 + start, end - start + 1);
	strt[end - start + 1] = '\0';
	return (strt);
}
